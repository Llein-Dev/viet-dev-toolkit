const fs = require('fs');
const path = require('path');
const { createTsConfig, createPackageJson, createReadme } = require('./common');

const group1 = require('./group1');
const group2 = require('./group2');
const group3 = require('./group3');
const group4 = require('./group4');
const group5 = require('./group5');

const allPackages = [...group1, ...group2, ...group3, ...group4, ...group5];
const rootDir = path.resolve(__dirname, '..', '..');

console.log(`Starting generation of ${allPackages.length} packages in ${rootDir}...`);

allPackages.forEach((pkg, index) => {
  const pkgDir = path.join(rootDir, pkg.folder);
  const srcDir = path.join(pkgDir, 'src');

  if (!fs.existsSync(pkgDir)) {
    fs.mkdirSync(pkgDir, { recursive: true });
  }
  if (!fs.existsSync(srcDir)) {
    fs.mkdirSync(srcDir, { recursive: true });
  }

  // 1. package.json
  const pkgJsonContent = createPackageJson({
    name: pkg.name,
    description: pkg.description,
    keywords: pkg.keywords
  });
  fs.writeFileSync(path.join(pkgDir, 'package.json'), pkgJsonContent, 'utf8');

  // 2. tsconfig.json
  fs.writeFileSync(path.join(pkgDir, 'tsconfig.json'), createTsConfig(), 'utf8');

  // 3. README.md
  const readmeContent = createReadme({
    name: pkg.name,
    description: pkg.description,
    category: pkg.category,
    usageCode: pkg.usageCode,
    apiList: pkg.apiList
  });
  fs.writeFileSync(path.join(pkgDir, 'README.md'), readmeContent, 'utf8');

  // 4. src/index.ts
  fs.writeFileSync(path.join(srcDir, 'index.ts'), pkg.code.trim() + '\n', 'utf8');

  console.log(`[${index + 1}/50] Generated: ${pkg.folder}`);
});

