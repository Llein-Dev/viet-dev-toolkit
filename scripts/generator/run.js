// Create Root package.json
const rootPackageJson = {
  name: 'npm-micro-utilities-factory',
  version: '1.0.0',
  private: true,
  description: 'Collection of 50 Production-Ready Micro / Utility npm packages',
  workspaces: allPackages.map((p) => p.folder),
  scripts: {
    "build:all": "turbo run build || npm run build:each",
    "test:all": "turbo run test || npm run test:each"
  },
  devDependencies: {
    tsup: '^8.3.5',
    typescript: '^5.7.2',
    vitest: '^2.1.8'
  }
};
fs.writeFileSync(path.join(rootDir, 'package.json'), JSON.stringify(rootPackageJson, null, 2), 'utf8');

